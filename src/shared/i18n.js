/** True when `lang` defines `key` (used by the translation-coverage test). */
export function hasTranslation(key, lang) {
  return Object.hasOwn(STRINGS[lang] || {}, key)
}

export function setLanguage(lang) {
  _forcedLang = lang
}

function currentLang() {
  if (_forcedLang && STRINGS[_forcedLang]) return _forcedLang
  const nav = (navigator.language || 'en').split('-')[0]
  return STRINGS[nav] ? nav : 'en'
}

/**
 * Returns translated string with params substituted by plain text replacement.
 * WARNING: result MUST be placed into textContent or createElement, NEVER into innerHTML.
 * @param {string} key Translation key
 * @param {object} [params={}] Key-value pairs for {placeholder} substitution (text-only, no HTML)
 * @returns {string}
 */
export function t(key, params = {}) {
  const lang = currentLang()
  let str = STRINGS[lang][key]
  if (str === undefined) str = STRINGS.en[key]
  if (str === undefined) return key

  for (const [k, v] of Object.entries(params)) {
    str = str.replace(`{${k}}`, v)
  }
  return str
}
